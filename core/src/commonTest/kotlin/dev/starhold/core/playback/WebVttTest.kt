package dev.starhold.core.playback

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull
import kotlin.test.assertTrue

class WebVttTest {
    private val sample = """
        WEBVTT

        NOTE generated by Starhold

        1
        00:00:01.000 --> 00:00:04.000 align:middle
        Hello <i>world</i>

        00:01:02.500 --> 00:01:05.000
        Second line
        and another
    """.trimIndent()

    @Test
    fun parsesCues() {
        val cues = WebVtt.parse(sample)
        assertEquals(2, cues.size)
        assertEquals(1000L, cues[0].startMs)
        assertEquals(4000L, cues[0].endMs)
        assertEquals("Hello world", cues[0].text)
        assertEquals(62500L, cues[1].startMs)
        assertEquals("Second line\nand another", cues[1].text)
    }

    @Test
    fun shiftMovesCues() {
        val cues = WebVtt.parse(sample, shiftMs = 10_000)
        assertEquals(11_000L, cues[0].startMs)
        assertEquals(72_500L, cues[1].startMs)
    }

    @Test
    fun cuesBeforeZeroAfterShiftAreDropped() {
        val cues = WebVtt.parse(sample, shiftMs = -63_000)
        assertTrue(cues.none { it.endMs <= 0 })
    }

    @Test
    fun activeCueLookup() {
        val cues = WebVtt.parse(sample)
        assertEquals("Hello world", WebVtt.activeAt(cues, 2000)?.text)
        assertNull(WebVtt.activeAt(cues, 10_000))
        assertEquals("Second line\nand another", WebVtt.activeAt(cues, 63_000)?.text)
    }

    @Test
    fun tagsAndEntities() {
        val cues = WebVtt.parse("WEBVTT\n\n00:00:00.000 --> 00:00:01.000\nA &amp; B &lt;3\n")
        assertEquals("A & B <3", cues.single().text)
    }
}
